import type { Request, Response } from "express";
import { sdk } from "./_core/sdk.js";
import {
  getAnalysisReport,
  getClientProfileById,
  getClientProfileByUserId,
} from "./db.js";

export class FinalReportDeliveryError extends Error {
  constructor(
    public readonly status: number,
    message: string,
  ) {
    super(message);
    this.name = "FinalReportDeliveryError";
  }
}

export function finalReportFilename(clientName: string): string {
  const safeName = clientName
    .replace(/[^a-zA-Z0-9 _-]/g, "")
    .trim()
    .replace(/\s+/g, "-");
  return `Lifework-${safeName || "Report"}.pdf`;
}

/** A counsellor may inspect any report; a client may inspect only their own. */
export function canAccessFinalReport(
  user: { id?: number; role?: string },
  reportOwnerUserId: number,
): boolean {
  return user.role === "admin" || user.id === reportOwnerUserId;
}

export async function resolveAuthorisedFinalReport(req: Request): Promise<{
  clientName: string;
  pdfUrl: string;
}> {
  let user: Awaited<ReturnType<typeof sdk.authenticateRequest>> | null = null;
  try {
    user = await sdk.authenticateRequest(req);
  } catch {
    throw new FinalReportDeliveryError(401, "Unauthorised");
  }

  if (!user?.id) {
    throw new FinalReportDeliveryError(401, "Unauthorised");
  }

  const requestedClientId = req.params.clientId ?? "";
  const ownProfile = requestedClientId === "me"
    ? await getClientProfileByUserId(user.id)
    : null;
  const clientId = ownProfile?.id ?? Number.parseInt(requestedClientId, 10);

  if (!clientId || Number.isNaN(clientId)) {
    throw new FinalReportDeliveryError(400, "Invalid client ID");
  }

  const profile = ownProfile ?? await getClientProfileById(clientId);
  if (!profile) {
    throw new FinalReportDeliveryError(404, "Report recipient not found");
  }

  if (!canAccessFinalReport(user, profile.userId)) {
    throw new FinalReportDeliveryError(403, "Forbidden — you may view only your own report");
  }

  const report = await getAnalysisReport(profile.id);
  if (!report?.wowReportPdfUrl) {
    throw new FinalReportDeliveryError(404, "The final Lifework report is not ready yet");
  }

  const clientName = [profile.firstName, profile.lastName]
    .filter(Boolean)
    .join(" ") || "Client";

  return {
    clientName,
    pdfUrl: report.wowReportPdfUrl,
  };
}

/**
 * Delivers the stored PDF generated by the report pipeline. This deliberately
 * avoids re-rendering a second HTML layout at download time: the PDF has
 * already passed the report release preflight before it was stored.
 */
export async function streamAuthorisedFinalReport(
  req: Request,
  res: Response,
  disposition: "inline" | "attachment",
): Promise<void> {
  try {
    const { clientName, pdfUrl } = await resolveAuthorisedFinalReport(req);
    const upstream = await fetch(pdfUrl);
    if (!upstream.ok) {
      throw new FinalReportDeliveryError(502, "The stored Lifework report could not be retrieved");
    }

    const pdf = Buffer.from(await upstream.arrayBuffer());
    if (pdf.length === 0) {
      throw new FinalReportDeliveryError(502, "The stored Lifework report is empty");
    }

    res.setHeader("Content-Type", "application/pdf");
    res.setHeader("Content-Disposition", `${disposition}; filename="${finalReportFilename(clientName)}"`);
    res.setHeader("Content-Length", pdf.length);
    res.setHeader("X-Content-Type-Options", "nosniff");
    res.status(200).end(pdf);
  } catch (error) {
    const status = error instanceof FinalReportDeliveryError ? error.status : 500;
    const message = error instanceof Error ? error.message : "Failed to deliver final report";
    if (status >= 500) {
      console.error("[final-report-delivery]", message);
    }
    res.status(status).json({ error: message });
  }
}
